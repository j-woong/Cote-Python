"""
***로직***
1. 입력 변수
- n: 타일로 채워야 할 직사각형의 가로 길이

2. 핵심 변수
- dp: 가로 길이가 i일 때 직사각형을 채울 수 있는 모든 경우의 수를 저장할 누적 배열 변수

3. 핵심 로직
step1: 기저 조건 예외 처리 및 배열 생성
- 가로 길이가 2 이하일 때는 조합 가짓수가 n과 동일하므로 if n <= 2 분기를 통해 즉시 조기 반환함
- n+1 크기의 dp 배열을 생성하고 dp[1] = 1, dp[2] = 2로 기저 상태를 초기화함

step2: 타일링 점화식 누적 연산
- 3부터 n까지 가로 길이를 1씩 늘려가며 반복 순회함
- i번째 공간을 채우는 방법은 (i-1) 공간에서 세로 타일을 붙이거나, (i-2) 공간에서 가로 타일 2개를 붙이는 두 가지 경로의 합이므로 dp[i] = dp[i-1] + dp[i-2] 점화식을 적용함
- 가짓수가 거대해지는 것을 방어하기 위해 매 루프마다 1000000007로 나눈 나머지를 저장함

step3: 결과 반환
- 목적지 가로 길이에 해당하는 dp[n] 최종 가짓수를 반환함

4. 예외 처리
- 인덱스 아웃 오브 바운즈(IndexError) 및 연산 오버헤드 차단:
  n = 1일 때 예외 처리 분기가 없으면 dp[2] 할당 과정에서 배열 범위를 초과하여 효율성 테스트가 터짐을 인지하고 조기 반환(Early Return) 로직을 배치함. 또한 루프 외부가 아닌 내부에서 나머지 연산을 수행하여 거대 정수 덧셈 오버헤드를 최적화함
"""
def solution(n):
    if n <= 2:
        return n
    dp = [0] * (n+1)
    dp[1] = 1
    dp[2] = 2
    
    for i in range(3,n+1):
        dp[i] = (dp[i-1] + dp[i-2]) % 1000000007
    
    return dp[n]