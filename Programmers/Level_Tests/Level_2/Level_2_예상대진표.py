"""
***로직***
1. 입력 변수
- n: 대회 참가자 수 (2의 지수승, 최대 2^20)
- a: 참가자 A의 처음 번호
- b: 참가자 B의 처음 번호

2. 핵심 변수
- cnt: A와 B가 만나기까지 진행된 총 라운드 수 (결과값)
- math.ceil(): 소수점 이하를 올림하여 다음 라운드의 대진 번호를 계산하는 함수

3. 핵심 로직
step1: 라운드 매칭 루프 (while a != b)
- A와 B의 번호가 같아진다는 것은 같은 매치(대진)에서 만나 대결하게 됨을 의미하므로, 두 번호가 일치할 때까지 반복 탐색함
step2: 다음 라운드 번호 갱신
- 토너먼트 규칙에 따라 다음 라운드 번호는 '현재 번호 / 2'를 올림한 값과 같으므로, math.ceil(a / 2)와 math.ceil(b / 2)로 두 사람의 번호를 동시에 갱신함
step3: 카운트 누적 및 반환
- 매 라운드가 지나갈 때마다 cnt를 1씩 증가시키고, 루프를 탈출하는 순간의 총 라운드 수를 반환함

4. 예외 처리
- N의 크기에 따른 시간 초과 방지:
  대회 참가자 N이 아무리 커도(최대 약 105만 명), 라운드가 진행될 때마다 탐색 범위가 절반씩 줄어드는 이진 분할 구조 법칙이 성립함. 따라서 O(log N)의 로그 시간 복잡도로 효율성 테스트를 압도적인 성능으로 통과함
"""
import math
def solution(n,a,b):
    cnt = 0
    
    while a != b:
        a = math.ceil(a / 2)
        b = math.ceil(b / 2)
        cnt += 1
        
    return cnt
        
        

    